export function getCardArtwork(
  gameMode: GameMode,
  suit: SuitType,
  rank: number,
): number | undefined {
  const key = `${suit}_${rank}`;
  // The current arena still deals Chkobba cards for both menu choices; identify
  // Rami artwork only for standard French suits so Tunisian cards stay correct.
  const isStandardSuit = ['clubs', 'diamonds', 'hearts', 'spades'].includes(suit);
  if (isStandardSuit) return RAMI_ARTWORK[key];
  return CHKOBBA_ARTWORK[key];
}